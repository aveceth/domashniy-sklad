const norm=s=>String(s||'').trim().toLocaleLowerCase('ru').replace(/ё/g,'е');
const valid=r=>Array.isArray(r)&&r.length===2&&r.every(n=>Number.isInteger(n)&&n>=0);
export function estimateShelfLife(name,location,{opened=false}={}){
 const n=norm(name);if(!n)return null;
 const matched=rows.filter(r=>r.terms.some(term=>n.includes(norm(term))));
 const rule=matched.sort((a,b)=>Math.max(...b.terms.map(t=>norm(t).length))-Math.max(...a.terms.map(t=>norm(t).length))).find(r=>valid(opened?(location==='fridge'?r.openedFridge:location==='pantry'?r.openedPantry:null):r[location]));
 if(!rule)return null;
 const range=opened?(location==='fridge'?rule.openedFridge:rule.openedPantry):rule[location];
 return {minDays:range[0],maxDays:range[1],days:range[0],match:rule.terms[0],opened};
}
